// 生徒のログイン画面（login.js）のテスト：node tests/login-test.js
const fs = require('fs');
const { JSDOM } = require('jsdom');
const ok = (c, l) => { console.log((c ? 'OK  ' : 'NG  ') + l); if (!c) process.exitCode = 1; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const dom = new JSDOM('<!doctype html><body></body>', { url: 'https://block-ai-assistant.pages.dev/app/', runScripts: 'outside-only' });
const w = dom.window;
const calls = [];
let closed = false;
w.BlockAIHost = { post: (m) => { if (m.kind === 'close') closed = true; } };
w.fetch = async (url, opt) => {
  const body = opt && opt.body ? JSON.parse(opt.body) : {};
  calls.push({ url, body, auth: opt && opt.headers && opt.headers.authorization });
  const res = (o, s) => ({ status: s || 200, json: async () => o });
  if (url === '/api/health') return res({ ok: true, auth: true });
  if (body.action === 'login') return body.password === 'init1234' ? res({ ok: true, token: 'a'.repeat(64), user: { id: 'kids01', role: 'student', name: 'たろう' }, mustChange: true }) : res({ ok: false, error: 'IDかパスワードがちがいます' }, 401);
  if (body.action === 'password') return body.password.length >= 6 ? res({ ok: true }) : res({ ok: false, error: '短い' }, 400);
  if (body.action === 'logout') return res({ ok: true });
  return res({ ok: false }, 401);
};
w.eval(fs.readFileSync('public/app/login.js', 'utf8'));
(async () => {
  await w.BlockAuth.ready;
  const lg = w.document.querySelector('.lg');
  const fL = lg.querySelector('.f-login');
  const fC = lg.querySelector('.f-change');
  ok(!lg.hidden && !fL.hidden, 'ログインのしくみがあると、最初にログイン画面が出る');
  fL.elements.uid.value = 'kids01'; fL.elements.password.value = 'bad';
  fL.dispatchEvent(new w.Event('submit', { cancelable: true })); await wait(20);
  ok(/ちがいます/.test(fL.querySelector('.err').textContent), 'まちがえると理由が出る');
  fL.elements.password.value = 'init1234';
  fL.dispatchEvent(new w.Event('submit', { cancelable: true })); await wait(20);
  ok(!fC.hidden && fC.querySelector('.oldw').hidden, '初めてなら、パスワードを決める画面になる（いまのパスワードは聞かない）');
  ok(w.localStorage.getItem('blockai:session') === 'a'.repeat(64), '合言葉を保存する');
  fC.elements.password.value = 'abcdef1'; fC.elements.again.value = 'abcdef2';
  fC.dispatchEvent(new w.Event('submit', { cancelable: true })); await wait(20);
  ok(/ちがって/.test(fC.querySelector('.err').textContent), '確認がちがうと止める');
  fC.elements.again.value = 'abcdef1';
  let ev = null; w.addEventListener('blockai-auth', (e) => { ev = e.detail; });
  fC.dispatchEvent(new w.Event('submit', { cancelable: true })); await wait(20);
  const pc = calls.find((c) => c.body.action === 'password');
  ok(lg.hidden && pc.body.old === 'init1234' && pc.auth === 'Bearer ' + 'a'.repeat(64), '変えると画面が消える（いまのパスワードと合言葉を送る）');
  ok(ev && ev.user.name === 'たろう' && w.BlockAuth.user().id === 'kids01', 'ログインしたことをほかの画面に知らせる');
  await w.BlockAuth.logout();
  ok(!lg.hidden && !w.localStorage.getItem('blockai:session'), 'ログアウトで合言葉を消し、ログイン画面にもどる');
  lg.querySelector('.back').click();
  ok(closed, '「Scratchにもどる」で閉じる');
  process.exit();
})();
