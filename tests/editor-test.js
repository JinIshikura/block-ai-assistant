// 入力サポート（editorassist.js）のテスト：node tests/editor-test.js
const fs = require('fs');
const { JSDOM } = require('jsdom');
const R = '/home/claude/block-ai-assistant/public/app/';
const dom = new JSDOM('<!doctype html><body><div class="ed"><div class="wrap" style="position:relative"><textarea></textarea></div></div></body>', { runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.eval(fs.readFileSync(R + 'codeconv.js', 'utf8'));
w.eval(fs.readFileSync(R + 'editorassist.js', 'utf8'));
const ta = w.document.querySelector('textarea');
const A = w.EditorAssist.attach({ ta, wrap: ta.parentNode, barAfter: ta.parentNode });
const ok = (c, l) => { console.log((c ? 'OK  ' : 'NG  ') + l); if (!c) process.exitCode = 1; };
const set = (v, a, b) => { ta.value = v; ta.focus(); ta.setSelectionRange(a, b === undefined ? a : b); };
const key = (k, o = {}) => { const e = new w.KeyboardEvent('keydown', Object.assign({ key: k, bubbles: true, cancelable: true }, o)); ta.dispatchEvent(e); return e.defaultPrevented; };
const type = (s) => { for (const ch of s) { if (!key(ch)) { const p = ta.selectionStart; ta.setRangeText(ch, p, ta.selectionEnd, 'end'); ta.dispatchEvent(new w.Event('input', { bubbles: true })); } } };
const pop = () => ta.parentNode.querySelector('.ea-pop');
const bar = () => ta.parentNode.parentNode.querySelector('.ea-bar');

set('', 0); type('go_to(');
ok(ta.value === 'go_to()' && ta.selectionStart === 6, 'かっこを自動で閉じる: ' + JSON.stringify(ta.value));
type('0, 170)');
ok(ta.value === 'go_to(0, 170)', '閉じかっこは上書きする: ' + ta.value);
set('say_for()', 8); key('Backspace');
ok(ta.value === 'say_for', '空のかっこはペアで消す: ' + ta.value);
set('    while True:', 15); key('Enter');
ok(ta.value === '    while True:\n        ', ':のあとは1段深く: ' + JSON.stringify(ta.value));
set('        ', 8); key('Backspace');
ok(ta.value === '    ', '字下げの Backspace は4文字ずつ: ' + JSON.stringify(ta.value));
set('if a:\nb\nc', 0, 10); key('Tab');
ok(ta.value === '    if a:\n    b\n    c', '複数行の Tab: ' + JSON.stringify(ta.value));
key('Tab', { shiftKey: true });
ok(ta.value === 'if a:\nb\nc', '複数行の Shift+Tab: ' + JSON.stringify(ta.value));
set('a\nb', 0, 3); key('/', { ctrlKey: true });
ok(ta.value === '# a\n# b', 'Ctrl+/ でコメント: ' + JSON.stringify(ta.value));
key('/', { ctrlKey: true });
ok(ta.value === 'a\nb', 'もう一度でもどる');
set('得点＝得点＋１', 7); ta.dispatchEvent(new w.Event('input', { bubbles: true }));
ok(ta.value === '得点=得点+1', '全角の記号・数字を半角に: ' + ta.value);
ok(/半角に直した/.test(bar().textContent), '直したことを案内バーで知らせる');
set('print("１２３")', 13); ta.dispatchEvent(new w.Event('input', { bubbles: true }));
ok(ta.value === 'print("１２３")', '文字列の中の全角はそのまま');
set('print（"あ"）', 11); ta.dispatchEvent(new w.Event('input', { bubbles: true }));
ok(ta.value === 'print("あ")', '全角のかっこは直す: ' + ta.value);
set('    ', 4); type('ch');
const names = [...pop().querySelectorAll('.ea-item b')].map((b) => b.textContent);
ok(!pop().hidden && names.some((n) => /^change_y\(/.test(n)), '入力候補が出る: ' + names.slice(0, 5).join(' / '));
const idx = names.findIndex((n) => /^change_y\(/.test(n));
for (let k = 0; k < idx; k++) key('ArrowDown');
key('Enter');
ok(ta.value === '    change_y()' && ta.selectionStart === 13, '候補をえらぶと入り、かっこの中にカーソル: ' + JSON.stringify(ta.value));
ok(/y座標を〇ずつ変える/.test(bar().textContent), '案内バーに使い方が出る: ' + bar().textContent);
set('得点 = 0\n', 9); type('得');
ok(!pop().hidden && [...pop().querySelectorAll('.ea-item b')].some((b) => b.textContent === '得点'), '自分で作った変数も候補に出る');
key('Escape');
ok(pop().hidden, 'Esc で閉じる');
set('', 0); type('@when_f'); key('Enter');
ok(ta.value === '@when_flag_clicked\ndef script1():\n    ', 'はじまりの候補は def まで入る: ' + JSON.stringify(ta.value));
set('x = "', 5); type('"');
ok(ta.value === 'x = ""' || ta.value === 'x = "', '引用符の中で引用符');
set('', 0); type('"');
ok(ta.value === '""' && ta.selectionStart === 1, '引用符も自動で閉じる');
type('"');
ok(ta.value === '""' && ta.selectionStart === 2, '閉じ引用符は上書き');
